import fixture from '../__fixtures__/frames.json';
import { applyJsonPatch, InvalidPatch } from '../patch';
import { parseConversationView, parseWatchFrame, WireError, isSnapshotFrame } from '../types';
import type { JsonPatchOp, JsonValue } from '../types';

describe('applyJsonPatch', () => {
  it('adds to the array end (index and "-"), replaces nested, removes', () => {
    const doc = { a: [1, 2], n: { x: 1, y: 2 } };
    const out = applyJsonPatch(doc, [
      { op: 'add', path: '/a/2', value: 3 },
      { op: 'add', path: '/a/-', value: 4 },
      { op: 'replace', path: '/n/x', value: 9 },
      { op: 'remove', path: '/n/y' },
      { op: 'remove', path: '/a/0' },
    ]);
    expect(out).toEqual({ a: [2, 3, 4], n: { x: 9 } });
    expect(doc).toEqual({ a: [1, 2], n: { x: 1, y: 2 } });
  });

  it('inserts mid-array and handles escaped keys', () => {
    const out = applyJsonPatch({ 'a/b': { '~k': 1 }, l: [1, 3] } as JsonValue, [
      { op: 'replace', path: '/a~1b/~0k', value: 2 },
      { op: 'add', path: '/l/1', value: 2 },
      { op: 'add', path: '/new~1key', value: true },
    ]);
    expect(out).toEqual({ 'a/b': { '~k': 2 }, l: [1, 2, 3], 'new/key': true });
  });

  it('safely sets __proto__ as an own key', () => {
    const out = applyJsonPatch({} as JsonValue, [{ op: 'add', path: '/__proto__', value: { p: 1 } }]) as Record<string, unknown>;
    expect(Object.keys(out)).toEqual(['__proto__']);
    expect(({} as Record<string, unknown>).p).toBeUndefined();
  });

  it('keeps identity of untouched subtrees', () => {
    const doc = { left: { deep: [1, 2] }, right: { v: 1 } };
    const out = applyJsonPatch(doc, [{ op: 'replace', path: '/right/v', value: 2 }]);
    expect(out.left).toBe(doc.left);
    expect(out.right).not.toBe(doc.right);
  });

  it.each<[string, JsonPatchOp]>([
    ['missing path', { op: 'replace', path: '/nope', value: 1 }],
    ['missing parent', { op: 'add', path: '/a/b/c', value: 1 }],
    ['index out of range', { op: 'add', path: '/l/5', value: 1 }],
    ['bad index', { op: 'replace', path: '/l/x', value: 1 }],
    ['replace at end', { op: 'replace', path: '/l/2', value: 1 }],
    ['no leading slash', { op: 'remove', path: 'l' }],
    ['remove root', { op: 'remove', path: '' }],
    ['scalar parent', { op: 'add', path: '/s/x', value: 1 }],
  ])('throws InvalidPatch: %s', (_n, op) => {
    expect(() => applyJsonPatch({ l: [1, 2], s: 'str' } as JsonValue, [op])).toThrow(InvalidPatch);
  });

  it('replaces the root', () => {
    expect(applyJsonPatch({ a: 1 }, [{ op: 'replace', path: '', value: [1] }])).toEqual([1]);
  });
});

describe('engine frames fixture (generated by engine/src/watch)', () => {
  it('snapshot + patches reproduce the engine final view', () => {
    let view: JsonValue = fixture.initial as JsonValue;
    let last = 0;
    for (const raw of fixture.frames) {
      const f = parseWatchFrame(raw);
      expect(f.cursor).toBeGreaterThan(last);
      last = f.cursor;
      if (isSnapshotFrame(f)) throw new Error('unexpected snapshot');
      view = applyJsonPatch(view, f.patch);
    }
    expect(view).toEqual(fixture.final);
    expect(Object.keys((view as { toolOutput: object }).toolOutput)).toEqual(['t/1~x']);
  });

  it('parses a view and rejects malformed wire data', () => {
    expect(parseConversationView(fixture.initial).entries).toEqual([]);
    expect(() => parseConversationView({ ...fixture.initial, entries: 'x' })).toThrow(WireError);
    expect(() => parseWatchFrame({ cursor: 1 })).toThrow(WireError);
    expect(() => parseWatchFrame({ cursor: 1, patch: [{ op: 'move', path: '/a' }] })).toThrow(WireError);
    expect(() => parseWatchFrame({ cursor: 'x', patch: [] })).toThrow(WireError);
  });
});
