"""Knowledge Chunk model for vector search over document content.

Part of Frontier-Inspired Platform Simplification (Phase C).
Chunks are generated by splitting documents and embedding them
for semantic similarity search via pgvector.
"""
import uuid

from sqlalchemy import (
    Column, ForeignKey, Text, Integer, Index
)
from sqlalchemy.dialects.postgresql import UUID as PGUUID, JSONB
from sqlalchemy.orm import relationship
from pgvector.sqlalchemy import Vector

from app.models import Base


class KnowledgeChunk(Base):
    """A chunk of a document for vector search.

    Documents are split into overlapping chunks, each embedded
    with text-embedding-3-small (1536 dimensions) for semantic search.
    """
    __tablename__ = "knowledge_chunks"

    id = Column(PGUUID(as_uuid=True), primary_key=True, default=uuid.uuid4)
    tenant_id = Column(
        PGUUID(as_uuid=True),
        ForeignKey("tenants.id", ondelete="CASCADE"),
        nullable=False,
        index=True,
        comment="Tenant this chunk belongs to"
    )
    document_id = Column(
        PGUUID(as_uuid=True),
        ForeignKey("knowledge_documents.id", ondelete="CASCADE"),
        nullable=False,
        index=True,
        comment="Source document"
    )
    knowledge_base_id = Column(
        PGUUID(as_uuid=True),
        ForeignKey("knowledge_bases.id", ondelete="CASCADE"),
        nullable=False,
        index=True,
        comment="KB this chunk belongs to (denormalized for fast search)"
    )
    content = Column(
        Text,
        nullable=False,
        comment="Chunk text content"
    )
    chunk_index = Column(
        Integer,
        nullable=False,
        comment="Position of this chunk in the document"
    )
    embedding = Column(
        Vector(1536),
        nullable=True,
        comment="Vector embedding for similarity search (1536 dimensions)"
    )
    chunk_metadata = Column(
        JSONB,
        server_default='{}',
        comment="Chunk metadata: page number, section, etc."
    )

    # Relationships
    document = relationship("KnowledgeDocument", back_populates="chunks")

    __table_args__ = (
        Index(
            'ix_knowledge_chunks_embedding',
            'embedding',
            postgresql_using='hnsw',
            postgresql_with={'m': 16, 'ef_construction': 64},
            postgresql_ops={'embedding': 'vector_cosine_ops'}
        ),
    )

    def __repr__(self) -> str:
        return f"<KnowledgeChunk(id={self.id}, doc={self.document_id}, index={self.chunk_index})>"

    def to_dict(self) -> dict:
        return {
            "id": str(self.id),
            "tenant_id": str(self.tenant_id),
            "document_id": str(self.document_id),
            "knowledge_base_id": str(self.knowledge_base_id),
            "content": self.content,
            "chunk_index": self.chunk_index,
            "metadata": self.chunk_metadata or {},
        }
